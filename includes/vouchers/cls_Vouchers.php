class Vouchers extends BasicVoucher implements DefaultVoucherForm, DefaultVoucherPrint, DefaultVoucherReport, DefaultVoucherPrintAdditionalFormatting
{
    private float $VoucherTotal = 0;

    public function __construct()
    {
        parent::__construct("vc_voucher", "vc_voucher_data", "voucher_id", [
            VoucherType::BRV,
            VoucherType::BPV,
            VoucherType::CRV,
            VoucherType::CPV
        ]);

        $this->setAutoPrint(true);
    }

    /**
     * Returns weather counter account should be cash or bank
     * @param $VoucherTypeId
     * @return bool|string Cash, Bank
     */

    function getCounterAccountType($VoucherTypeId)
    {
        switch($VoucherTypeId) {
            case VoucherType::BPV:
            case VoucherType::BRV:
                return "Bank";

            case VoucherType::CPV:
            case VoucherType::CRV:
                return "Cash";

            default:
                return false;
        }
    }

    public function initForSave()
    {
        parent::initForSave(); // TODO: Change the autogenerated stub

        $oSalary = new Salary();
        $oSalary->deleteSalaryLoanInstallmentByDistinctId($this->getDistinctId());
    }

    protected function saveTransactionEntries()
    {
        $SelectData = $this->getData();
        $oSalary = new Salary();
        $oSMSTemplates = new SMSTemplates();
        $oLedger = $this->getLedgerObject();

        $RowDetails = $this->getDetails();
        $CashBankId = $RowDetails['cash_bank_id'];

        while ($Row = DBQM::fetch_assoc($SelectData))
        {
            $Row['currency_rate'] = $Row['currency_rate'] > 0 ? $Row['currency_rate'] : 1;
            $Amount = VoucherType::isVoucherTypeReceipt($this->getVoucherType()) ? ((float)$Row['amount'] * -1) : $Row['amount'];
            $WHT = (float)$Row['wht_amount'];

            $ChequePrefix = !empty($Row['cheque_number']) ? "Cheque #: ".$Row['cheque_number']."\nCheque Date: ".DateDecode($this->getDateTime())."\n" : '';

            $oLedger->saveData($Row['account_id'], ($Amount + $WHT) / $Row['currency_rate'], $Row['currency_rate'], $ChequePrefix.$Row['description'], $CashBankId);
            $oLedger->saveData($CashBankId, "-".$Amount, 1, $ChequePrefix.$Row['description'], $Row['account_id']);
            $oLedger->saveData(getConstantAccount()->getWHT(), "-".$WHT, 1, $ChequePrefix.": WHT", $Row['account_id']);

            if (!empty($RowDetails['loan_id']))
            {
                $oSalary->registerLoanInstallmentViaVouchers($RowDetails['distinct_id'], $RowDetails['loan_id'], $Row['amount'], $RowDetails['voucher_date']);
            }

            $Amount = ($Row['amount'] / $Row['currency_rate']);
            $this->VoucherTotal += $Row['amount'];

            /* ***************** SMS ********************* */
            if (VoucherType::isVoucherTypeReceipt($this->getVoucherType()))
            {
                $oSMSTemplates->UserPaymentReceived($Row['account_id'], $Amount * -1,$ChequePrefix.$Row['line_description'], DateDecode($RowDetails['voucher_date'], "M d, Y"), $this->isEdit());
            }
            else
            {
                $oSMSTemplates->UserPaymentDone($Row['account_id'], $Amount, $ChequePrefix.$Row['line_description'], DateDecode($RowDetails['voucher_date'], "M d, Y"), $this->isEdit());
            }
            /* ***************** SMS ********************* */
        }
    }

    function getVoucherPrintUtilsClass(): BasicVoucherPrintUtils
    {
        $oBasicVoucherPrintUtils = new BasicVoucherPrintUtils();
        $oBasicVoucherPrintUtils->calcTotals(["amount"]);

        if (in_array($this->getVoucherType(), [VoucherType::CPV, VoucherType::CRV]))
            $oBasicVoucherPrintUtils->setHideColumns(['cheque_number', 'cheque_date', 'wht_amount', 'currency_rate']);

        if ($this->getVoucherType() == VoucherType::CPV)
            $oBasicVoucherPrintUtils->setIsSignatureRequire(true);

        return $oBasicVoucherPrintUtils;
    }

    function getFormattedColumnValue($ColumnName, $Value): string|null
    {
        if ($ColumnName == 'description')
            return nl2br($Value);
        else
            return null;
    }

    function getVoucherFormUtils(): BasicVoucherFormUtils
    {
        $oFormUtils = new BasicVoucherFormUtils();
        $HiddenFields = ['loan_id', 'currency_rate'];

        $oFormUtils->attachJS("../js_live/vouchers/payment_receipt.min.js");
        $oFormUtils->addAdditionalColumns(0, 'current_balance', 'float', 'amount', 'text-right');
        $oFormUtils->setColumnDisplayType('account_id', new FormFieldTypeAccount('current_balance', 'currency_rate'));
        $oFormUtils->setAutocomplete('cash_bank_id', Autocomplete::TYPE_ACCOUNT_BY_COA, $this->getCounterAccountType($this->getVoucherType()) == 'Bank' ? [getConstantCategory()->getBank()] : [getConstantCategory()->getCashInHand()]);

        $oFormUtils->setColumnWidth([
            'account_id' => '30%',
            'amount' => '10%',
            'current_balance' => '10%',
            'currency_rate' => '7%',
            'wht_amount' => '7%',
            'cheque_number' => '17%',
            'cheque_date' => '10%'
        ]);

        if ($this->getCounterAccountType($this->getVoucherType()) == 'Cash')
        {
            $HiddenFields[] = 'cheque_number';
            $HiddenFields[] = 'cheque_date';
            $HiddenFields[] = 'wht_amount';
        }

        $oFormUtils->showColumnTotal(['amount', 'wht_amount']);
        $oFormUtils->setHiddenFields($HiddenFields);
        $oFormUtils->setRequiredFields(["cash_bank_id"]);
        return $oFormUtils;
    }

    function getVoucherTotal(): float
    {
        return $this->VoucherTotal;
    }

    function getReportFilters(): BasicVoucherReportFilters
    {
        $oReportFilter = new BasicVoucherReportFilters();
        $oReportFilter->setFilter('voucher_date', 'Date', 'date');
        $oReportFilter->setFilter('voucher_number', 'Voucher #', 'int');
        $oReportFilter->setFilter('voucher_type_id', 'Voucher Type', 'select', [
            VoucherType::CPV => VoucherType::getName(VoucherType::CPV),
            VoucherType::BPV => VoucherType::getName(VoucherType::BPV),
            VoucherType::CRV => VoucherType::getName(VoucherType::CRV),
            VoucherType::BRV => VoucherType::getName(VoucherType::BRV)
        ]);
        $oReportFilter->setFilter('account_id', 'Account', '', Autocomplete::TYPE_ACCOUNT);
        $oReportFilter->setFilter('description', 'Description', '');

        return $oReportFilter;
    }

    function getSearchQuery(): mysqli_result
    {
        $Where = '';

        if (empty($_GET['voucher_number']))
        {
            $Where .= UtilsQueryMaker::date("di.voucher_date", $_GET['date_from'], $_GET['date_till']);
            $Where .= UtilsQueryMaker::like("di.voucher_type_id", $_GET['voucher_type_id']);
            $Where .= UtilsQueryMaker::equal("a.id", $_GET['account_id']);
            $Where .= CostCenter::getFilterSql("di.cost_center_id", true);
            $Where .= UtilsQueryMaker::like("vd.description", $_GET['description']);
        }
        else
        {
            $Where .= UtilsQueryMaker::like("di.voucher_number", $_GET['voucher_number']);
            $Where .= UtilsQueryMaker::like("di.voucher_type_id", $_GET['voucher_type_id']);
        }

        return DBQM::query("
                    SELECT
                        di.voucher_date,
                        di.voucher_number,
                        di.voucher_type_id,
                        di.voucher_total,
                        di.is_draft,
                        vt.abbr,
                        cb.name AS cash_bank_name,
                        v.id,
                        v.distinct_id,
                        di.is_deleted,
                        get_voucher_data_account_names_by_voucher_id(v.id) AS voucher_data_account_names,
                        get_cost_center_name(di.cost_center_id) as cost_center_name
                    FROM
                        vt_voucher_type vt,
                        distinct_id di,
                        vc_voucher v
                        LEFT JOIN
                            vc_voucher_data vd ON v.id = vd.voucher_id
                        LEFT JOIN
                            acc_accounts cb ON cb.id = v.cash_bank_id
                        LEFT JOIN
                            acc_accounts a ON vd.account_id = a.id
                    WHERE
                        di.id = v.distinct_id AND
                        di.voucher_type_id = vt.id
                        {$Where}
                    GROUP BY 
                        v.id 
                    ORDER BY 
                        di.voucher_date DESC, di.voucher_number DESC
        ");
    }

    function getReportTableColumn(): BasicVoucherReportTableColumn
    {
        $oTableColumn = new BasicVoucherReportTableColumn();
        $oTableColumn->addColumn('voucher_date', 'Date', BasicVoucherReportTableColumn::TYPE_DATE);
        $oTableColumn->addColumn('abbr', 'Voucher Type');
        $oTableColumn->addColumn('voucher_number', 'Voucher #', BasicVoucherReportTableColumn::TYPE_INT);
        $oTableColumn->addColumn('cash_bank_name', 'Cash/Bank');
        $oTableColumn->addColumn('voucher_data_account_names', 'Accounts');
        $oTableColumn->addColumn('voucher_total', 'Total', BasicVoucherReportTableColumn::TYPE_FLOAT);
        $oTableColumn->addColumn('cost_center_name', 'Cost Center');

        return $oTableColumn;
    }
}